func TestAdviseShowsTheEvidenceBehindAReviewDecision(t *testing.T) {
	// A share is a snapshot; the decision needs the shape of the traffic. This is only possible
	// from a real log, which is why it is not offered for --ua-counts.
	var log strings.Builder
	for i := 0; i < 30; i++ {
		log.WriteString(`1.1.1.1 - - [01/Sep/2026:1` + string(rune('0'+i%10)) +
			`:00:00 +0000] "GET /archive/page HTTP/1.1" 200 1 "-" "Mozilla/5.0 (compatible; SomeSpider/1.0)"` + "\n")
	}
	for i := 0; i < 70; i++ {
		log.WriteString(`2.2.2.2 - - [01/Sep/2026:12:00:00 +0000] "GET / HTTP/1.1" 200 1 "-" "Mozilla/5.0 (Windows NT 10.0) Chrome/148"` + "\n")
	}
	p := writeTemp(t, "access.log", log.String())

	code, _, stderr := runCLI("advise", "--log", p)
	if code != 0 {
		t.Fatalf("exit code = %d, stderr: %s", code, stderr)
	}
	if !strings.Contains(stderr, "REVIEW") || !strings.Contains(stderr, "SomeSpider") {
		t.Fatalf("SomeSpider is 30%% of the traffic and unknown: it must come up for review:\n%s", stderr)
	}
	if !strings.Contains(stderr, "/archive/page") {
		t.Errorf("the paths it asked for are the argument, and must be shown:\n%s", stderr)
	}
	if !strings.Contains(stderr, "over") {
		t.Errorf("the time span must be shown: a crawl spread over hours is not a burst:\n%s", stderr)
	}
}

