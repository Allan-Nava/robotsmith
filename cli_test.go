func TestJSONOutputIsValidAndCarriesItsSchema(t *testing.T) {
	// A pipeline pins the schema: it is the only stable promise, because the prose is free to change.
	counts := writeTemp(t, "ua.txt", "5000 Mozilla/5.0 (compatible; GPTBot/1.4)\n1000 Mozilla/5.0 (compatible; Googlebot/2.1)\n")
	broken := writeTemp(t, "broken.txt", "User-agent: *\n\nDisallow: /admin/\n")

	cases := []struct {
		name   string
		args   []string
		schema string
	}{
		{"check", []string{"check", "--json", serveRobots(t, healthyRobots, 200)}, "robotsmith.check/1"},
		{"lint", []string{"lint", "--json", broken}, "robotsmith.lint/1"},
		{"advise", []string{"advise", "--json", "--ua-counts", counts}, "robotsmith.advise/1"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			_, stdout, _ := runCLI(c.args...)
			var got map[string]any
			if err := json.Unmarshal([]byte(stdout), &got); err != nil {
				t.Fatalf("stdout is not valid JSON: %v\n%s", err, stdout)
			}
			if got["schema"] != c.schema {
				t.Errorf("schema = %v, expected %s", got["schema"], c.schema)
			}
		})
	}
}

