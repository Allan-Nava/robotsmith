func TestCrawlersJSONIsOrderedLikeTheEvaluation(t *testing.T) {
	// The first matching pattern wins, so the order IS part of the answer: a consumer must get it
	// in evaluation order, not sorted for looks.
	_, stdout, _ := runCLI("crawlers", "--json")
	var rep struct {
		Schema string `json:"schema"`
		Rules  []struct {
			Pattern string `json:"pattern"`
			Family  string `json:"family"`
			Policy  string `json:"policy"`
			Token   string `json:"token"`
		} `json:"rules"`
	}
	if err := json.Unmarshal([]byte(stdout), &rep); err != nil {
		t.Fatalf("not valid JSON: %v\n%s", err, stdout)
	}
	if rep.Schema != "robotsmith.crawlers/1" {
		t.Errorf("schema = %q", rep.Schema)
	}
	if len(rep.Rules) < 40 {
		t.Fatalf("expected the whole table, got %d rules", len(rep.Rules))
	}
	if rep.Rules[0].Token != "Googlebot" {
		t.Errorf("first rule = %+v: the allowlist must come first, or a generic pattern swallows it",
			rep.Rules[0])
	}
	var iGPTBot, iChatGPTUser int
	for i, r := range rep.Rules {
		switch r.Token {
		case "GPTBot":
			iGPTBot = i
		case "ChatGPT-User":
			iChatGPTUser = i
		}
	}
	if iChatGPTUser > iGPTBot {
		t.Error("ChatGPT-User must be listed before GPTBot: their UA contains \"openai\" and the " +
			"order is what keeps a user-triggered fetch out of the training bucket")
	}
}

