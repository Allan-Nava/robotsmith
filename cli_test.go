func TestAdviseCompareReachesTheJSONDocument(t *testing.T) {
	prev := writeTemp(t, "prev.json", `{"schema":"robotsmith.advise/1","total_requests":100000,
	  "decisions":[{"name":"GPTBot","policy":"block","requests":2000,"share":2.0}]}`)
	counts := writeTemp(t, "ua.txt", "8000 Mozilla/5.0 (compatible; GPTBot/1.4)\n92000 Mozilla/5.0 (Windows NT 10.0) Chrome/148\n")
	_, stdout, _ := runCLI("advise", "--json", "--ua-counts", counts, "--compare", prev)
	var rep struct {
		Comparison *struct {
			PreviousTotal int64 `json:"previous_total_requests"`
			Movements     []struct {
				Name      string  `json:"name"`
				Direction string  `json:"direction"`
				Was       float64 `json:"was_share"`
				Now       float64 `json:"now_share"`
				Factor    float64 `json:"factor"`
			} `json:"movements"`
		} `json:"comparison"`
	}
	if err := json.Unmarshal([]byte(stdout), &rep); err != nil {
		t.Fatal(err)
	}
	if rep.Comparison == nil || rep.Comparison.PreviousTotal != 100000 {
		t.Fatalf("comparison = %+v", rep.Comparison)
	}
	var found bool
	for _, m := range rep.Comparison.Movements {
		if m.Name != "GPTBot" {
			continue
		}
		found = true
		if m.Direction != "grew" || m.Was != 2.0 || m.Now != 8.0 || m.Factor != 4.0 {
			t.Errorf("movement = %+v", m)
		}
	}
	if !found {
		t.Errorf("movements = %+v", rep.Comparison.Movements)
	}
}

func TestAdviseWritesAReportTheExtensionChooses(t *testing.T) {
	counts := writeTemp(t, "ua.txt", "5000 Mozilla/5.0 (compatible; GPTBot/1.4)\n5000 Mozilla/5.0 (compatible; Googlebot/2.1)\n")
	dir := t.TempDir()
	for _, name := range []string{"report.html", "report.pdf"} {
		dest := filepath.Join(dir, name)
		code, stdout, stderr := runCLI("advise", "--ua-counts", counts, "--host", "example.com", "--report", dest)
		if code != 0 {
			t.Fatalf("%s: exit %d, stderr: %s", name, code, stderr)
		}
		b, err := os.ReadFile(dest)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if len(b) < 500 {
			t.Errorf("%s is %d bytes: suspiciously empty", name, len(b))
		}
		if !strings.Contains(stderr, dest) {
			t.Errorf("%s: writing a file must be said out loud:\n%s", name, stderr)
		}
		// ⚠️ The report is an extra, not a replacement: stdout stays the file you deploy, so
		// `advise --report r.html > robots.txt` keeps working.
		if !strings.HasPrefix(stdout, "# robots.txt generated by robotsmith") {
			t.Errorf("%s: stdout must still be the robots.txt:\n%s", name, stdout)
		}
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "report.pdf")); !bytes.HasPrefix(b, []byte("%PDF")) {
		t.Error("the .pdf must actually be a PDF")
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "report.html")); !bytes.Contains(b, []byte("<svg")) {
		t.Error("the .html must carry the inline chart")
	}
}

